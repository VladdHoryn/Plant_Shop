#!/usr/bin/env bash
# Goodhart crash test: what happens to a coverage-only gate when coverage becomes the team KPI.
# 1. baseline catalog-service; 2. the same module plus a test that executes code but asserts nothing
# (scripts/goodhart/CoverageOnlyGamingTest.java, copied in for this run only and removed afterwards).
# Each state is checked by a coverage-only gate and by the balanced gate (coverage AND mutation score).
# Output: docs/goodhart-demo.md.     Usage: COVERAGE_MIN=60 MUTATION_MIN=50 ./scripts/goodhart-demo.sh
set -uo pipefail
cd "$(dirname "$0")/.."

MODULE=catalog-service
FIXTURE=scripts/goodhart/CoverageOnlyGamingTest.java
TARGET=$MODULE/src/test/java/com/plantshop/catalog/service/CoverageOnlyGamingTest.java
OUT=docs/goodhart-demo.md
COVERAGE_MIN=${COVERAGE_MIN:-60}
MUTATION_MIN=${MUTATION_MIN:-50}
if [ -z "${JAVA_HOME:-}" ]; then
  for jdk in "$HOME"/.jdks/*21*; do [ -x "$jdk/bin/java" ] && export JAVA_HOME="$jdk" && break; done
fi
# Stale classes of a deleted test stay in target/ and keep counting (incremental build), so they go too
STALE=$MODULE/target/test-classes/com/plantshop/catalog/service/CoverageOnlyGamingTest*
remove_fixture() { rm -f "$TARGET" $STALE; }
remove_fixture
trap remove_fixture EXIT

measure() {
  ./mvnw -B -q -Pquality verify -pl "$MODULE" -am -Dtest='!*IntegrationTest' -Dsurefire.failIfNoSpecifiedTests=false \
    > target-goodhart-build.log 2>&1 || { echo "build failed, see target-goodhart-build.log" >&2; exit 1; }
  rm -f target-goodhart-build.log
}
gates() {
  printf '\nCoverage-only gate (the KPI):\n'
  COVERAGE_MIN=$COVERAGE_MIN MUTATION_MIN=0 ./scripts/quality-gate.sh "$MODULE" | tail -2
  printf '\nBalanced gate:\n'
  COVERAGE_MIN=$COVERAGE_MIN MUTATION_MIN=$MUTATION_MIN ./scripts/quality-gate.sh "$MODULE"
}

{
  echo "# Goodhart crash test: coverage as a KPI"
  echo
  echo "Generated by \`scripts/goodhart-demo.sh\` on $(date '+%Y-%m-%d %H:%M'), module \`$MODULE\`,"
  echo "thresholds COVERAGE_MIN=$COVERAGE_MIN, MUTATION_MIN=$MUTATION_MIN. Unedited tool output."
  echo
  echo "## 1. Baseline (the real test suite)"
  echo '```console'
  measure; gates
  echo '```'
  echo
  echo "## 2. After adding an assertion-free test (\`$FIXTURE\`)"
  echo '```console'
  cp "$FIXTURE" "$TARGET"
  measure; gates
  echo '```'
  echo
  echo "Surviving mutants with the gaming test (each one is a bug no test would notice):"
  echo '```console'
  grep -o "status='SURVIVED'.*</mutatedMethod><methodDescription>.*</lineNumber><mutator>[^<]*" \
       "$MODULE/target/pit-reports/mutations.xml" \
    | sed -E "s#.*<sourceFile>([^<]*)</sourceFile>.*<mutatedMethod>([^<]*)</mutatedMethod>.*<lineNumber>([0-9]*)</lineNumber><mutator>.*\.([A-Za-z]*)#\1:\3 \2 \4#" \
    | sort | uniq | head -15
  echo '```'
} | tee "$OUT"
