#!/usr/bin/env bash
# Reliability test of the static analyzer (Lizard): does the same code always give the same numbers?
#   Scenario A - file format: LF, CRLF, UTF-8 with BOM (business logic unchanged)
#   Scenario B - runner version: Python 3.8.20 (EOL) vs 3.13.17, Lizard 1.17.10 vs 1.24.3
# Logical metrics (NLOC, CCN, tokens) come from Lizard; physical ones (bytes, lines, SHA-256) from coreutils
# to show what does change. Every runner is an isolated container: no network, 1 CPU, 256 MB.
# Output: docs/reliability-report.md.
#   ./scripts/reliability-test.sh [path/to/File.java]
set -uo pipefail
cd "$(dirname "$0")/.."

FILE=${1:-user-service/src/main/java/com/plantshop/user/service/PersonalDataExportService.java}
OUT=docs/reliability-report.md
WORK=target/reliability
NAME=$(basename "$FILE")
# runner = "<python>:<lizard>"; the first one is the pinned project runner (tools/lizard/Dockerfile)
RUNNERS=("3.13.17:1.24.3" "3.13.17:1.17.10" "3.8.20:1.24.3" "3.8.20:1.17.10")
export MSYS_NO_PATHCONV=1   # Git Bash on Windows: keep container paths as they are

image() { echo "plantshop/lizard:${2}-py${1}"; }

prepare_variants() {
  rm -rf "$WORK"; mkdir -p "$WORK"/lf "$WORK"/crlf "$WORK"/bom
  tr -d '\r' < "$FILE" > "$WORK/lf/$NAME"
  sed 's/$/\r/' "$WORK/lf/$NAME" > "$WORK/crlf/$NAME"
  { printf '\xEF\xBB\xBF'; cat "$WORK/lf/$NAME"; } > "$WORK/bom/$NAME"
}

build_runners() {
  for r in "${RUNNERS[@]}"; do
    docker build -q --build-arg PYTHON_VERSION="${r%%:*}" --build-arg LIZARD_VERSION="${r##*:}" \
      -t "$(image "${r%%:*}" "${r##*:}")" tools/lizard > /dev/null || exit 1
  done
}

# lizard <image> <variant> -> "NLOC functions sumCCN maxCCN tokens"
lizard_metrics() {
  docker run --rm --network none --cpus 1 --memory 256m -v "$(pwd -W 2>/dev/null || pwd)/$WORK/$2:/src:ro" "$1" \
    -l java "$NAME" 2>&1 | awk '
      $1 ~ /^[0-9]+$/ && $2 ~ /^[0-9]+$/ && $6 ~ /@/ { f++; ccn += $2; tok += $3; if ($2 > max) max = $2 }
      $1 ~ /^[0-9]+$/ && NF == 6 && $6 ~ /\.java$/ { nloc = $1 }
      END { printf "%s %d %d %d %d", nloc, f, ccn, max, tok }'
}

physical() {   # bytes lines sha256(short)
  printf '%s %s %s' "$(wc -c < "$WORK/$1/$NAME" | tr -d ' ')" "$(wc -l < "$WORK/$1/$NAME" | tr -d ' ')" \
    "$(sha256sum "$WORK/$1/$NAME" | cut -c1-12)"
}

row() {   # row <label> <image> <variant>
  read -r nloc fn ccn max tok < <(lizard_metrics "$2" "$3")
  read -r bytes lines sha < <(physical "$3")
  printf '| %s | %s | %s | %s | %s | %s | %s | %s | `%s` |\n' "$1" "$nloc" "$fn" "$ccn" "$max" "$tok" "$bytes" "$lines" "$sha"
}

header() {
  printf '| %s | NLOC | Functions | Σ CCN | max CCN | Tokens | Bytes | Lines | SHA-256 |\n' "$1"
  printf '|---|---|---|---|---|---|---|---|---|\n'
}

prepare_variants
build_runners
BASE=$(image 3.13.17 1.24.3)
{
  echo "# Reliability test of the static analyzer"
  echo
  echo "Generated by \`scripts/reliability-test.sh\` on $(date '+%Y-%m-%d %H:%M'). File under test: \`$FILE\`."
  echo "Lizard runs in containers built from \`tools/lizard/Dockerfile\` (\`--network none --cpus 1 --memory 256m\`)."
  echo "NLOC, functions, CCN and tokens are logical metrics computed by Lizard; bytes, lines and the hash describe"
  echo "the physical file."
  echo
  echo "## Scenario A: line endings and encoding (runner \`$BASE\`)"
  echo
  header "File format"
  row "LF (Unix)" "$BASE" lf
  row "CRLF (Windows)" "$BASE" crlf
  row "UTF-8 + BOM" "$BASE" bom
  echo
  echo "## Scenario B: runner version (file in LF)"
  echo
  header "Python / Lizard"
  for r in "${RUNNERS[@]}"; do row "Python ${r%%:*} / Lizard ${r##*:}" "$(image "${r%%:*}" "${r##*:}")" lf; done
  echo
  echo "## Scenario A x B: CRLF file under every runner"
  echo
  header "Python / Lizard"
  for r in "${RUNNERS[@]}"; do row "Python ${r%%:*} / Lizard ${r##*:}" "$(image "${r%%:*}" "${r##*:}")" crlf; done
} | tee "$OUT"
