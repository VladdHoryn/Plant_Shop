#!/usr/bin/env bash
# Stability test of a dynamic metric: does p95 of catalog-service change although the code does not?
# The same k6 load (perf/k6/catalog-search.js) runs against the same build in five conditions:
#   1-2 isolated (twice: natural variance), 3 noisy neighbour (CPU-hog containers compressing random data
#   on the same machine), 4 noisy neighbour + CPU limit on the service (docker update --cpus), 5 isolated again.
# The k6 thresholds are the performance quality gate (PASS/FAIL).
# Prerequisite: docker compose stack running.  Output: docs/stability-report.md
#   P95_MS=150 ERROR_RATE=0.01 VUS=20 DURATION=30s ./scripts/stability-test.sh
set -uo pipefail
cd "$(dirname "$0")/.."
export MSYS_NO_PATHCONV=1

SUT=plantshop-catalog-service
K6_IMAGE=grafana/k6:0.54.0
NOISE_IMAGE=alpine:3.20
OUT=docs/stability-report.md
WORK=target/stability
P95_MS=${P95_MS:-150}
ERROR_RATE=${ERROR_RATE:-0.01}
VUS=${VUS:-20}
DURATION=${DURATION:-30s}
LIMITED_CPUS=${LIMITED_CPUS:-0.25}
NOISE_JOBS=${NOISE_JOBS:-$(docker info --format '{{.NCPU}}')}
NETWORK=$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}}{{end}}' "$SUT")
HOST_DIR=$(pwd -W 2>/dev/null || pwd)

mkdir -p "$WORK"
cleanup() {
  docker rm -f $(docker ps -aq --filter label=plantshop.noise) > /dev/null 2>&1
  # "--cpus 0" is silently ignored by docker update; the CPU count of the machine means "no limit"
  docker update --cpus "$(docker info --format '{{.NCPU}}')" "$SUT" > /dev/null 2>&1
}
trap cleanup EXIT

k6() {   # k6 <name> <duration> - the load generator itself is pinned and resource-limited
  docker run --rm --network "$NETWORK" --cpus 1 --memory 512m \
    -e P95_MS="$P95_MS" -e ERROR_RATE="$ERROR_RATE" -e VUS="$VUS" -e DURATION="$2" \
    -v "$HOST_DIR/perf/k6:/scripts:ro" -v "$HOST_DIR/$WORK:/out" \
    "$K6_IMAGE" run --quiet --no-color --summary-export "/out/$1.json" /scripts/catalog-search.js > "$WORK/$1.log" 2>&1
}

noise_on() {
  for i in $(seq "$NOISE_JOBS"); do
    docker run -d --rm --label plantshop.noise "$NOISE_IMAGE" sh -c 'cat /dev/urandom | gzip -9 > /dev/null' > /dev/null
  done
}

value() {   # value <json> <metric> <stat>
  sed -n "/\"$2\"/,/}/p" "$1" | grep -o "\"$3\": *[0-9.e+-]*" | head -1 | sed 's/.*: *//'
}

run_case() {   # run_case <name> <label>
  local stats
  ( sleep 15; docker stats --no-stream --format '{{.CPUPerc}} {{.MemUsage}}' "$SUT" > "$WORK/$1.stats" ) &
  k6 "$1" "$DURATION"; local code=$?
  wait
  stats=$(cat "$WORK/$1.stats" 2>/dev/null)
  local j="$WORK/$1.json"
  awk -v l="$2" -v rps="$(value "$j" http_reqs rate)" -v med="$(value "$j" http_req_duration med)" \
      -v avg="$(value "$j" http_req_duration avg)" -v p95="$(value "$j" http_req_duration 'p(95)')" \
      -v p99="$(value "$j" http_req_duration 'p(99)')" -v max="$(value "$j" http_req_duration max)" \
      -v err="$(value "$j" http_req_failed value)" -v st="$stats" -v gate="$([ $code = 0 ] && echo PASS || echo FAIL)" \
      'BEGIN { printf "| %s | %.0f | %.1f | %.1f | **%.1f** | %.1f | %.1f | %.2f%% | %s | %s |\n", l, rps, med, avg, p95, p99, max, 100 * err, st, gate }'
}

{
  echo "# Stability test of the p95 response time"
  echo
  echo "Generated by \`scripts/stability-test.sh\` on $(date '+%Y-%m-%d %H:%M'). Target \`$SUT\`"
  echo "(\`GET /api/catalog/plants?careLevel=EASY&size=10\`), k6 \`$K6_IMAGE\` in its own container (1 CPU, 512 MB)"
  echo "on the compose network; $VUS VUs for $DURATION per run after a 15 s warm-up. Gate (k6 thresholds):"
  echo "\`p(95) < ${P95_MS} ms AND error rate < ${ERROR_RATE}\`. Code, data and load are identical in every run."
  echo "Noise: $NOISE_JOBS containers \`gzip -9\` of /dev/urandom; CPU limit: \`docker update --cpus $LIMITED_CPUS $SUT\`."
  echo "Service CPU/RAM sampled with \`docker stats\` in the middle of each run."
  echo
  echo "| Run | req/s | median ms | avg ms | p95 ms | p99 ms | max ms | errors | service CPU / RAM | Gate |"
  echo "|---|---|---|---|---|---|---|---|---|---|"
  k6 warmup 15s
  run_case isolated-1 "1. isolated"
  run_case isolated-2 "2. isolated (repeat)"
  noise_on
  run_case noise "3. noisy neighbour"
  docker update --cpus "$LIMITED_CPUS" "$SUT" > /dev/null
  run_case noise-cpu-limit "4. noisy neighbour + --cpus $LIMITED_CPUS"
  cleanup
  sleep 5
  run_case isolated-3 "5. isolated again"
} | tee "$OUT"
