#!/usr/bin/env bash
# Runs the Helm lab demonstration (environment, chart checks, install, release lifecycle,
# hook + release test) and records every command with its output in docs/helm-report.md.
#
# Prerequisites: minikube running with the ingress and metrics-server addons, helm 3,
# images built with scripts/build-images.sh.   Usage: ./scripts/helm-demo.sh
set -uo pipefail
cd "$(dirname "$0")/.."

CHART=helm/plantshop
RELEASE=plantshop
NS=plantshop-dev
OUT=docs/helm-report.md
PORT=18081
mkdir -p docs

# --- helpers ---------------------------------------------------------------------------------
section() { printf '\n## %s\n' "$1" >> "$OUT"; echo ">>> $1"; }
note()    { printf '\n%s\n' "$1" >> "$OUT"; }
run() {   # run '<command>'  - prints the command and its output into the report
  # sed adds the final newline that curl output lacks, so the closing fence stays on its own line
  { printf '\n```console\n$ %s\n' "$1"; eval "$1" 2>&1 | sed -e '$a\'; printf '```\n'; } >> "$OUT"
}

# GET <path> through the gateway Service. A fresh port-forward each time, because upgrades
# replace the pods a long-running port-forward is attached to.
gw() {
  local svc=$1 path=$2 pf
  kubectl -n "$NS" port-forward "svc/$svc" $PORT:"${3:-80}" > /dev/null 2>&1 &
  pf=$!
  sleep 3
  curl -s --max-time 10 "localhost:$PORT$path"
  kill $pf 2> /dev/null; wait $pf 2> /dev/null
}

# The pre-upgrade hook Job is deleted as soon as it succeeds; stream its log while it runs
capture_hook_log() {
  local end=$(( $(date +%s) + 120 ))
  until kubectl -n "$NS" logs -f "job/$RELEASE-pre-upgrade-check" > /tmp/plantshop-hook.log 2>/dev/null \
        || [ "$(date +%s)" -ge "$end" ]; do
    sleep 0.5
  done
}

cat > "$OUT" <<EOF
# Plant Shop Helm chart: lab report

Generated by \`scripts/helm-demo.sh\` on $(date '+%Y-%m-%d %H:%M'). Every block below is a command
that was actually run and its unedited output. Chart: \`$CHART\`, release \`$RELEASE\`, namespace \`$NS\`.
EOF

# --- 1. Environment --------------------------------------------------------------------------
section "1a-b. Helm and the cluster"
run 'helm version'
run 'minikube status'
run 'kubectl get nodes'

section "1c. The Lab 3 manifests still deploy and work"
run 'kubectl apply -f k8s/ | tail -5'
run 'for d in $(kubectl -n plantshop get deploy -o name); do kubectl -n plantshop rollout status $d --timeout=600s; done | tail -3'
NS=plantshop run "gw api-gateway /api/catalog/info"

section "1d. Remove the Lab 3 deployment (avoids conflicts, e.g. its fixed NodePort 30080, and frees memory)"
run 'kubectl delete -f k8s/ --wait=true | tail -3'
run 'kubectl get ns plantshop'

# --- 6. Environments -------------------------------------------------------------------------
section "6b. dev vs prod without installing anything (helm template)"
note "Object kinds rendered for each environment (hooks excluded):"
run "helm template $RELEASE $CHART -f $CHART/values-dev.yaml --no-hooks | grep '^kind:' | sort | uniq -c"
run "helm template $RELEASE $CHART -f $CHART/values-prod.yaml --no-hooks | grep '^kind:' | sort | uniq -c"
note "Lines that differ between the two renderings (the random DB password and the change-cause / checksum annotations filtered out):"
run "diff <(helm template $RELEASE $CHART -f $CHART/values-dev.yaml --no-hooks) <(helm template $RELEASE $CHART -f $CHART/values-prod.yaml --no-hooks) | grep -E '^[<>] +(name: $RELEASE-|# Source|replicas|image:|cpu|memory|type:|SHOP_NAME|JAVA_TOOL|KAFKA_HEAP|value: \"-Xm|host:)' | sed 's/^</dev: /; s/^>/prod:/'"

section "6c. Value precedence: values.yaml < -f files (left to right) < --set"
P="-s templates/catalog-service-deployment.yaml | grep -E '^  replicas|image: plantshop'"
run "helm template $RELEASE $CHART $P"
run "helm template $RELEASE $CHART -f $CHART/values-prod.yaml $P"
run "helm template $RELEASE $CHART -f $CHART/values-prod.yaml -f $CHART/values-dev.yaml $P"
run "helm template $RELEASE $CHART -f $CHART/values-prod.yaml --set catalogService.replicaCount=5 --set catalogService.image.tag=1.0.0 $P"

# --- 7. Test and install ---------------------------------------------------------------------
section "7a. Lint"
run "helm lint $CHART --strict"
run "helm lint $CHART --strict -f $CHART/values-dev.yaml"
run "helm lint $CHART --strict -f $CHART/values-prod.yaml"

section "7b. Generated manifests vs the Lab 3 manifests"
note "Objects of both, with the release prefix \"$RELEASE-\" removed from the chart's names:"
run "diff <(kubectl apply --dry-run=client -f k8s/ -o name | sort) <(helm template $RELEASE $CHART -n $NS --no-hooks | kubectl apply --dry-run=client -f - -o name | sed 's#/$RELEASE-#/#; s#/config\$#/plantshop-config#; s#/db-secret\$#/plantshop-db-secret#' | sort); echo \"diff exit code: \$?\""
note "The only extra object in Lab 3 is the Namespace; with Helm it is created by \`--create-namespace\`. \
Content differences, shown for the catalog-service Deployment: release-based names, the standard \
app.kubernetes.io/* labels instead of \`app:\`, a ConfigMap checksum annotation, and values instead of literals."
run "diff k8s/catalog-service-deployment.yaml <(helm template $RELEASE $CHART -n plantshop -s templates/catalog-service-deployment.yaml)"

section "7c. Install into its own namespace"
run "helm install $RELEASE $CHART -n $NS --create-namespace -f $CHART/values-dev.yaml --wait --timeout 10m"
run "kubectl -n $NS get deploy,svc,ingress,pvc"
run "gw $RELEASE-api-gateway /api/catalog/info"

section "7d. Releases, status and values"
run "helm list -n $NS"
run "helm status $RELEASE -n $NS | head -8"
run "helm get values $RELEASE -n $NS"

section "7e. Where Helm keeps the release state"
note "One Secret of type helm.sh/release.v1 per revision, in the release's namespace:"
run "kubectl -n $NS get secrets -l owner=helm --show-labels"
run "kubectl -n $NS get secret sh.helm.release.v1.$RELEASE.v1 -o jsonpath='{.data.release}' | base64 -d | base64 -d | gzip -d | head -c 300; echo ' ...'"

# --- 9b. Release test (elective) -------------------------------------------------------------
section "9b. Release test on the fresh install"
run "helm test $RELEASE -n $NS"
note "The test pod is deleted when it passes (\`hook-succeeded\`), so it never outlives the release."

# --- 8. Lifecycle ----------------------------------------------------------------------------
section "8a. Upgrade: new image tag with --set"
capture_hook_log &
run "helm upgrade $RELEASE $CHART -n $NS -f $CHART/values-dev.yaml --set catalogService.image.tag=1.1.0 --wait --timeout 10m | head -6"
wait
note "Output of the pre-upgrade hook Job during this upgrade (elective 9b):"
run 'cat /tmp/plantshop-hook.log'
run "kubectl -n $NS get deploy $RELEASE-catalog-service -o jsonpath='{.spec.template.spec.containers[0].image}'; echo"
run "gw $RELEASE-api-gateway /api/catalog/info"

section "8b. Upgrade to the prod values file"
capture_hook_log &
run "helm upgrade $RELEASE $CHART -n $NS -f $CHART/values-prod.yaml --wait --timeout 15m | head -6"
wait
run 'cat /tmp/plantshop-hook.log'
run "kubectl -n $NS get deploy,svc,ingress"
note "The database password was not passed: the Secret template reused the one already stored in the release (lookup)."
run "gw $RELEASE-api-gateway /api/catalog/info"

section "8c. Revision history"
run "helm history $RELEASE -n $NS"
note "Revision 1: install with values-dev.yaml. Revision 2: the same values plus \`catalogService.image.tag=1.1.0\` \
(only the catalog-service Deployment changed). Revision 3: values-prod.yaml (every image 1.1.0, 3 gateway and \
3 catalog replicas, bigger resources, a production JVM in the ConfigMap, LoadBalancer instead of NodePort + Ingress)."
run "helm get values $RELEASE -n $NS --revision 2"
run "diff <(helm get manifest $RELEASE -n $NS --revision 2 | grep -E '^kind:|replicas:|image:|type:') <(helm get manifest $RELEASE -n $NS --revision 3 | grep -E '^kind:|replicas:|image:|type:')"

section "8d. Rollback to revision 2"
capture_hook_log &
run "helm rollback $RELEASE 2 -n $NS --wait --timeout 15m"
wait
run 'cat /tmp/plantshop-hook.log'
run "helm history $RELEASE -n $NS"
run "kubectl -n $NS get deploy,svc,ingress"
run "gw $RELEASE-api-gateway /api/catalog/info"
run "helm test $RELEASE -n $NS"

section "9b. The pre-upgrade hook blocks an upgrade when a database is down"
run "kubectl -n $NS scale deploy/$RELEASE-payment-db --replicas=0"
run "kubectl -n $NS wait --for=delete pod -l app.kubernetes.io/component=payment-db --timeout=120s"
run "helm upgrade $RELEASE $CHART -n $NS -f $CHART/values-dev.yaml --set config.shopName=Blocked --wait --timeout 5m"
run "kubectl -n $NS logs job/$RELEASE-pre-upgrade-check --tail=8"
run "helm history $RELEASE -n $NS | tail -3"
note "The failed revision changed nothing: the ConfigMap still has the old shop name."
run "kubectl -n $NS get configmap $RELEASE-config -o jsonpath='{.data.SHOP_NAME}'; echo"
run "kubectl -n $NS scale deploy/$RELEASE-payment-db --replicas=1"

section "8e. Uninstall with one command"
run "helm uninstall $RELEASE -n $NS --wait"
note "The failed hook Job from the previous step is not part of the release (Helm never deletes hooks on \
uninstall); it was kept for debugging, so remove it, then check the namespace:"
run "kubectl -n $NS delete job -l app.kubernetes.io/instance=$RELEASE --ignore-not-found"
run 'sleep 10'
run "kubectl -n $NS get all,configmap,secret,pvc,ingress"
run "kubectl get pv | grep $NS || echo 'no persistent volumes left'"
run "helm list -n $NS"
note "Only \`kube-root-ca.crt\` is left; Kubernetes puts it into every namespace."

echo "Report written to $OUT"
