#!/usr/bin/env bash
# Runs the lab demonstration (cluster check, deploy, lifecycle, diagnostics) against minikube
# and records every command with its output in docs/k8s-report.md.
#
# Prerequisites: minikube running with the ingress and metrics-server addons,
# images built with scripts/build-images.sh.   Usage: ./scripts/k8s-demo.sh
set -uo pipefail
cd "$(dirname "$0")/.."

NS=plantshop
OUT=docs/k8s-report.md
PORT=18080
mkdir -p docs

# --- helpers ---------------------------------------------------------------------------------
section() { printf '\n## %s\n' "$1" >> "$OUT"; echo ">>> $1"; }
note()    { printf '\n%s\n' "$1" >> "$OUT"; }
run() {   # run '<command>'  - prints the command and its output into the report
  # sed adds the final newline that curl output lacks, so the closing fence stays on its own line
  { printf '\n```console\n$ %s\n' "$1"; eval "$1" 2>&1 | sed -e '$a\'; printf '```\n'; } >> "$OUT"
}
info() { curl -s --max-time 5 "localhost:$PORT/api/catalog/info"; }

# Requests /api/catalog/info every 0.2 s for $1 seconds and reports how many failed
availability_probe() {
  local end=$(( $(date +%s) + $1 )) ok=0 fail=0 code
  while [ "$(date +%s)" -lt "$end" ]; do
    code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "localhost:$PORT/api/catalog/info")
    if [ "$code" = 200 ]; then ok=$((ok + 1)); else fail=$((fail + 1)); fi
    sleep 0.2
  done
  echo "requests: $((ok + fail)), HTTP 200: $ok, failed: $fail"
}

start_port_forward() {
  kubectl -n $NS port-forward svc/api-gateway $PORT:80 > /dev/null 2>&1 &
  PF_PID=$!
  sleep 4
}
trap 'kill ${PF_PID:-} 2>/dev/null' EXIT

cat > "$OUT" <<EOF
# Plant Shop on Kubernetes: lab report

Generated by \`scripts/k8s-demo.sh\` on $(date '+%Y-%m-%d %H:%M'). Every block below is a command
that was actually run and its unedited output. The application is reached through
\`kubectl port-forward svc/api-gateway $PORT:80\` (the same gateway Service that is exposed by
NodePort 30080 and by the Ingress).
EOF

# --- 2. Cluster ------------------------------------------------------------------------------
section "2. Cluster"
run 'minikube status'
run 'kubectl get nodes -o wide'
run 'kubectl get pods -n kube-system'
run "minikube addons list | grep -E 'ingress |metrics-server'"
run "minikube image ls | grep plantshop | sort"

# --- 5. Deploy -------------------------------------------------------------------------------
section "5a. Apply all manifests with one command"
run 'kubectl apply -f k8s/'
run "for d in \$(kubectl -n $NS get deploy -o name); do kubectl -n $NS rollout status \$d --timeout=600s; done"

section "5b. Created objects"
run "kubectl -n $NS get deployments"
run "kubectl -n $NS get replicasets"
run "kubectl -n $NS get pods -o wide"
run "kubectl -n $NS get services"
run "kubectl -n $NS get ingress,pvc,configmap,secret"

start_port_forward
section "5c. The application answers"
note "The same URLs work in a browser: http://localhost:$PORT/... while the port-forward runs, \
\`minikube service api-gateway -n $NS --url\`, or http://plantshop.local/ through the Ingress with \`minikube tunnel\`."
run "curl -s 'localhost:$PORT/api/catalog/plants?size=3'"
run "curl -s localhost:$PORT/api/catalog/categories"
run 'info'

section "5d. ConfigMap and Secret values inside the container"
run "kubectl -n $NS exec deploy/catalog-service -c catalog-service -- printenv SHOP_NAME SHOP_CURRENCY CONFIG_SERVER_URL KAFKA_BOOTSTRAP_SERVERS DB_USERNAME DB_PASSWORD"
note "The application uses them: \`shopName\` and \`currency\` in /api/catalog/info come from the ConfigMap, \
and the services could log in to PostgreSQL with the credentials from the Secret (the catalog query above succeeded)."
run "kubectl -n $NS get secret plantshop-db-secret -o jsonpath='{.data.DB_PASSWORD}' | base64 -d; echo"
run "kubectl -n $NS exec deploy/catalog-db -- sh -c 'echo POSTGRES_USER=\$POSTGRES_USER POSTGRES_DB=\$POSTGRES_DB'"

# --- 6. Lifecycle ----------------------------------------------------------------------------
section "6a. Self-healing: delete a pod"
VICTIM=$(kubectl -n $NS get pods -l app=catalog-service -o jsonpath='{.items[0].metadata.name}')
run "kubectl -n $NS get pods -l app=catalog-service"
run "kubectl -n $NS delete pod $VICTIM --wait=false"
run "sleep 2; kubectl -n $NS get pods -l app=catalog-service"
run "kubectl -n $NS rollout status deploy/catalog-service --timeout=300s"
run "kubectl -n $NS get pods -l app=catalog-service"
run "kubectl -n $NS get events --field-selector involvedObject.kind=ReplicaSet --sort-by=.lastTimestamp | tail -4"

section "6b. Scaling and load distribution"
run "kubectl -n $NS scale deploy/catalog-service --replicas=3"
run "kubectl -n $NS rollout status deploy/catalog-service --timeout=300s"
note "The gateway learns about new instances from Eureka within a few seconds."
run 'sleep 15'
run "kubectl -n $NS get pods -l app=catalog-service -o wide"
run "for i in \$(seq 1 12); do info | grep -o '\"pod\":\"[^\"]*\"'; done | sort | uniq -c"
run "kubectl top pods -n $NS -l app=catalog-service"

section "6c. Rolling update to 1.1.0 (with an availability probe running)"
availability_probe 150 > /tmp/plantshop-probe.txt &
PROBE_PID=$!
sleep 3
run "kubectl -n $NS set image deploy/catalog-service catalog-service=plantshop/catalog-service:1.1.0"
run "kubectl -n $NS annotate deploy/catalog-service kubernetes.io/change-cause='Update image to 1.1.0' --overwrite"
run "kubectl -n $NS rollout status deploy/catalog-service --timeout=600s"
run "kubectl -n $NS get replicasets -l app=catalog-service"
run "kubectl -n $NS get pods -l app=catalog-service"
run "for i in \$(seq 1 6); do info | grep -o '\"version\":\"[^\"]*\",\"pod\":\"[^\"]*\"'; done"

section "6e. Availability during the update"
note "Requests sent to /api/catalog/info every 0.2 s through the gateway while the update above was running:"
wait $PROBE_PID
run 'cat /tmp/plantshop-probe.txt'

section "6d. Rollout history and rollback"
run "kubectl -n $NS rollout history deploy/catalog-service"
REV=$(kubectl -n $NS get deploy catalog-service -o jsonpath='{.metadata.annotations.deployment\.kubernetes\.io/revision}')
run "kubectl -n $NS rollout history deploy/catalog-service --revision=$REV"
availability_probe 120 > /tmp/plantshop-probe.txt &
PROBE_PID=$!
sleep 3
run "kubectl -n $NS rollout undo deploy/catalog-service"
run "kubectl -n $NS rollout status deploy/catalog-service --timeout=600s"
run "kubectl -n $NS rollout history deploy/catalog-service"
run "kubectl -n $NS get deploy catalog-service -o jsonpath='{.spec.template.spec.containers[0].image}'; echo"
run 'info'
wait $PROBE_PID
note "Availability probe during the rollback:"
run 'cat /tmp/plantshop-probe.txt'
run "kubectl -n $NS scale deploy/catalog-service --replicas=2"

# --- 7. Diagnostics --------------------------------------------------------------------------
section "7a. A non-existent image tag"
run "kubectl -n $NS set image deploy/catalog-service catalog-service=plantshop/catalog-service:9.9.9"
run "kubectl -n $NS annotate deploy/catalog-service kubernetes.io/change-cause='Broken tag 9.9.9' --overwrite"
run 'sleep 45'
run "kubectl -n $NS get pods -l app=catalog-service"
note "maxUnavailable: 0 keeps the old pods running, so the application stays up while the new pod cannot start:"
run 'info'

section "7b. Finding the cause: describe and events"
BAD=$(kubectl -n $NS get pods -l app=catalog-service --no-headers | grep -E 'ImagePull|ErrImage' | awk '{print $1}' | head -1)
run "kubectl -n $NS describe pod $BAD | sed -n '/^Containers:/,/^    Ready:/p'"
run "kubectl -n $NS describe pod $BAD | sed -n '/^Events:/,\$p'"
run "kubectl -n $NS get events --field-selector involvedObject.name=$BAD --sort-by=.lastTimestamp"

section "7c. Logs and a shell inside the container"
run "kubectl -n $NS logs deploy/catalog-service -c catalog-service --tail=15"
run "kubectl -n $NS logs deploy/catalog-service -c wait-for-dependencies"
note "Interactive shell: \`kubectl -n $NS exec -it deploy/catalog-service -c catalog-service -- bash\`. \
The same commands, run non-interactively so they can be recorded:"
run "kubectl -n $NS exec deploy/catalog-service -c catalog-service -- bash -c 'whoami; hostname; ls -l /app; java -version 2>&1 | head -1'"

section "7d. Fix and verify"
run "kubectl -n $NS rollout undo deploy/catalog-service"
run "kubectl -n $NS annotate deploy/catalog-service kubernetes.io/change-cause='Rollback after broken tag' --overwrite"
run "kubectl -n $NS rollout status deploy/catalog-service --timeout=600s"
run "kubectl -n $NS get pods -l app=catalog-service"
run "kubectl -n $NS rollout history deploy/catalog-service"
run 'info'

echo "Report written to $OUT"
